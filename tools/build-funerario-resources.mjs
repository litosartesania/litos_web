// Deterministic, network-free resource bundle, shared by page and standalone preview.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
const catalog=JSON.parse(readFileSync('assets/funerario/configuracion/catalogo.json','utf8'));
const paths=[...catalog.materials.flatMap(m=>m.variants.map(v=>v.path)),...catalog.fonts.map(f=>f.path),...catalog.ornaments.map(o=>o.path)];
const resources={};
for(const path of paths){
 const bytes=readFileSync(path);
 const mime=path.endsWith('.webp')?'image/webp':path.endsWith('.png')?'image/png':path.endsWith('.woff2')?'font/woff2':'image/svg+xml';
 resources[path]=mime==='image/svg+xml'?bytes.toString('utf8'):`data:${mime};base64,${bytes.toString('base64')}`;
}
// Keep the six copyright notices and OFL texts with every embedded-font copy,
// including the single-file offline preview, in readable source comments.
const licenses=catalog.fonts.map(f=>'/* '+f.name+' — FONT LICENSE\n'+readFileSync(f.license,'utf8').replace(/\r\n?/g,'\n').split('\n').map(line=>line.trimEnd()).join('\n').replaceAll('*/','* /')+'\n*/\n').join('');
const output='/* Generated by tools/build-funerario-resources.mjs. No network or visitor data. */\n'+licenses+'window.LitosMemorialData='+JSON.stringify({catalog,resources}).replaceAll('<','\\u003c')+';\n';
writeFileSync('funerario-recursos.js',output);
const publicPaths=[...paths,...catalog.fonts.map(f=>f.license),'assets/funerario/configuracion/catalogo.json'];
const files=publicPaths.sort().map(path=>{const b=readFileSync(path);return {path,bytes:b.length,sha256:createHash('sha256').update(b).digest('hex')};});
writeFileSync('docs/FUNERARIO_ASSETS_MANIFEST.json',JSON.stringify({version:1,origin:'Original generated textures and original generic vectors; OFL fonts.',files},null,2)+'\n');
console.log(`Bundled ${paths.length} resources, ${output.length} bytes; export works offline.`);
